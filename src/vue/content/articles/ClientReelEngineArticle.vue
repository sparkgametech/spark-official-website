            兩款規則相同的遊戲，可能因為停輪節奏差了幾十毫秒，觀感就從「乾脆俐落」變成「拖泥帶水」。
            好的滾輪引擎必須提供<strong>絲滑流暢、物理真實</strong>的旋轉體驗，
            而且這個體驗要可調校、可重現，而不是反覆試錯碰出來的。
        </p>
