        <h2><i class="fa-solid fa-circle-question" aria-hidden="true"></i>為什麼 RNG 安全如此重要？</h2>
        <p>
            <strong>隨機數生成器（Random Number Generator, RNG）</strong>是博弈遊戲公平性的基石。
            每一次老虎機的 Spin、每一張牌的發放、每一個骰子的結果，都取決於 RNG 產生的隨機數。
            如果 RNG 存在偏差、可預測性或被操控的可能，整個遊戲的公平性就無法保證。
        </p>
        <p>
            在合規市場中，RNG 必須通過第三方認證機構（如 <strong>GLI</strong> 或 <strong>BMM</strong>）的嚴格審計，
            確保其符合統計學上的隨機性標準。這不僅是技術要求，更是遊戲合規上線的法規門檻。
        </p>
        <p>
            要理解 RNG 的設計取捨，必須先建立<strong>威脅模型（Threat Model）</strong>的概念。
            我們假設的攻擊者並不是隨機亂試的玩家，而是一個具備完整逆向工程能力、能夠長期蒐集大量結果樣本、
            甚至掌握部分程式邏輯的對手。在這個假設下，任何「因為別人猜不到所以安全」的設計都不成立；
            隨機性的安全必須來自數學結構本身，而不是資訊不對稱。
            這也是為什麼所有安全決策都應該建立在「攻擊者知道演算法、只是不知道金鑰與內部狀態」的前提上。
        </p>

        <h2><i class="fa-solid fa-triangle-exclamation" aria-hidden="true"></i>為什麼一般的偽隨機數不夠用</h2>
        <p>
            大多數程式語言內建的隨機函式，其設計目標是<strong>速度與統計均勻性</strong>，而不是安全性。
            以常見的線性同餘產生器（LCG）為例，它的下一個狀態由當前狀態經過一次乘法與加法即可得出；
            攻擊者只要觀察到少數幾個連續輸出，就能解出內部參數並完整預測未來的整個序列。
            即使是統計品質相當優秀的 Mersenne Twister，也只需要蒐集約數百個連續輸出，
            就能還原出完整的內部狀態並反推整條序列。
        </p>
        <p>
            關鍵在於：<strong>通過統計檢定不等於不可預測</strong>。
            一個序列可以在卡方檢定、Runs Test 上表現完美，卻仍然是完全可預測的。
            統計均勻性衡量的是「輸出看起來像不像隨機」，而密碼學安全衡量的是「知道歷史輸出後能否推導未來」，
            這是兩個獨立的性質。博弈遊戲同時需要兩者，缺一不可。
        </p>

        <h2><i class="fa-solid fa-lock" aria-hidden="true"></i>密碼學安全的偽隨機數生成器（CSPRNG）</h2>
        <p>
            博弈遊戲的 RNG 必須使用<strong>密碼學安全的偽隨機數生成器（Cryptographically Secure PRNG）</strong>，
            而非一般程式語言提供的標準隨機函式。兩者的關鍵差異在於：
        </p>
        <ul>
            <li><strong>不可預測性</strong>：即使知道之前的所有輸出，也無法預測下一個數值</li>
            <li><strong>不可回溯性</strong>：即使知道當前狀態，也無法推導出之前的輸出</li>
            <li><strong>熵源品質</strong>：使用作業系統核心維護的熵池作為隨機性來源，而非時間戳等可預測的種子</li>
        </ul>
        <p>
            在實作上，我們採用作業系統提供的密碼學隨機來源（在 Linux 上即 <code>getrandom()</code> 這類系統呼叫，
            在其他平台則是對應的核心隨機介面）作為隨機數的底層來源，確保每個隨機數都具備密碼學等級的安全性。
            不自行實作演算法、盡量把信任邊界推向作業系統與硬體，本身就是一項重要的安全設計原則：
            核心的隨機子系統經過大量公開審查與長期實戰驗證，遠比任何自製的替代方案可靠。
        </p>

        <h2><i class="fa-solid fa-atom" aria-hidden="true"></i>熵源的取得與品質評估</h2>
        <p>
            CSPRNG 只是把少量真隨機「延展」成大量不可預測的位元，它本身不創造隨機性。
            真正的隨機性來自<strong>熵源（Entropy Source）</strong>，也就是物理上不可預測的事件。
            現代作業系統會從多個獨立通道持續收集熵：CPU 的硬體隨機指令、中斷發生的時間抖動、
            磁碟與網路 I/O 的完成時間、以及各種難以被外部觀測的微觀時序差異。
            這些原始樣本會先進入熵池，經過雜湊混合後才對外提供。
        </p>
        <p>
            評估熵源品質時，真正該看的指標是<strong>最小熵（Min-Entropy）</strong>，
            也就是「最可能出現的那個值的出現機率」所對應的熵值，而不是平均意義上的夏農熵。
            這是保守估計：因為攻擊者猜測時一定優先猜最可能的值。相關評估方法在
            <strong>NIST SP 800-90B</strong> 中有完整定義，包含獨立同分佈檢驗與一系列最小熵估計器。
        </p>
        <p>
            實務上有幾個容易被忽略的熵源風險，值得在設計階段就納入考量：
        </p>
        <ul>
            <li><strong>開機早期的熵匱乏</strong>：系統剛啟動時熵池尚未累積足夠的隨機性，
                此時取得的隨機數品質可能不足。正確做法是使用會阻塞直到熵池就緒的介面，而非為了避免延遲而降級</li>
            <li><strong>虛擬化環境的熵稀缺</strong>：虛擬機缺乏直接的硬體中斷來源，熵累積速度遠低於實體機，
                必要時需要透過虛擬化層的熵傳遞機制補足</li>
            <li><strong>映像複製導致的狀態重複</strong>：從同一個系統映像複製出多個執行實例時，
                若熵池狀態一併被複製，多個實例可能在啟動初期產生相同的隨機序列</li>
            <li><strong>單一來源的信任風險</strong>：不應完全依賴任何單一硬體隨機來源，
                多來源混合能確保即使其中一個通道品質下降，整體輸出的不可預測性仍然成立</li>
        </ul>

        <h2><i class="fa-solid fa-filter" aria-hidden="true"></i>消除模數偏差：Rejection Sampling</h2>
        <p>
            當我們需要一個範圍在 <code>[0, max)</code> 的隨機整數時，最直覺的做法是 <code>rand() % max</code>。
            然而，這個做法會產生<strong>模數偏差（Modulo Bias）</strong>：當隨機數的上限不能被 max 整除時，
            某些結果的出現機率會略高於其他結果。
        </p>
        <p>
            偏差的數學成因其實很直觀。假設底層隨機數的取值範圍是 <code>0</code> 到 <code>N-1</code> 共 N 個等機率的值，
            而我們想要映射到 <code>0</code> 到 <code>max-1</code>。如果 N 不能被 max 整除，
            那麼 N 除以 max 會餘下 <code>r = N mod max</code> 個「多出來」的值，
            這些多餘的值會被分配給前 r 個結果。於是前 r 個結果各自對應
            <code>⌊N/max⌋ + 1</code> 個原始值，其餘結果只對應 <code>⌊N/max⌋</code> 個，
            前者的出現機率因此系統性地偏高。
        </p>
        <p>
            用一個極端的小例子最容易看清楚：若原始隨機數只有 <code>0~9</code> 十種可能，要映射到三個結果，
            則 0、1、2 各對應四個原始值中的一個較多者：結果 0 與 1 的機率是 4/10，結果 2 卻只有 2/10。
            這種偏差不會隨著取樣次數增加而消失，反而會在大樣本下被統計檢定精準地捕捉出來。
        </p>
        <p>
            雖然在 max 遠小於隨機數範圍時偏差極小，但在博弈遊戲中，任何統計上的不均勻都可能成為審計風險。
            更重要的是，這種偏差是<strong>結構性而非隨機性</strong>的：它有明確方向、可被累積、也可被逆向推導利用。
            因此我們採用 <strong>Rejection Sampling（拒絕採樣）</strong>來完全消除偏差：
        </p>
        <div class="formula-block">
            <code>threshold = MaxUint64 - (MaxUint64 % max)<br/>
do {<br/>
&nbsp;&nbsp;value = crypto_rand_uint64()<br/>
} while (value >= threshold)<br/>
result = value % max</code>
        </div>
        <p>
            這個演算法的原理是：丟棄會造成偏差的那些隨機數（落在不完整的最後一個 max 區間的值），
            只保留能產生完美均勻分佈的結果。被拒絕的機率極低（小於 <code>max / 2^64</code>），
            對效能幾乎沒有影響，但確保了<strong>數學上完美的均勻分佈</strong>。
        </p>

        <h2><i class="fa-solid fa-seedling" aria-hidden="true"></i>種子管理與防碰撞</h2>
        <p>
            在高併發的遊戲伺服器中，RNG 的種子（Seed）管理是另一個關鍵安全點。
            如果兩個玩家的 RNG 使用相同的種子，就會產生相同的遊戲結果序列。
        </p>
        <p>
            為了防止種子碰撞，我們採用以下策略：
        </p>
        <ul>
            <li><strong>多元熵源混合</strong>：將系統時間、遞增計數器、硬體隨機數等多個來源組合作為種子</li>
            <li><strong>原子遞增保護</strong>：使用原子操作的遞增素數因子，確保即使在極短時間內建立多個 RNG 實例，種子也不會重複</li>
            <li><strong>獨立實例</strong>：每個遊戲會話使用獨立的 RNG 實例，避免跨玩家的狀態共享</li>
        </ul>
        <p>
            更完整的思路是把種子視為一個有<strong>生命週期</strong>的敏感資產，而不是一個一次性的初始化參數。
            這個生命週期大致可以分為四個階段，每個階段各有必須守住的原則：
        </p>
        <ul>
            <li><strong>生成</strong>：種子必須具備足夠的熵長度。若種子空間只有 32 位元，
                即使演算法本身無懈可擊，攻擊者也只需窮舉約四十億種可能就能還原整個序列。
                安全強度取決於最弱的一環，而種子往往就是那一環</li>
            <li><strong>使用</strong>：種子只存在於產生它的執行環境記憶體中，不跨進程傳遞、不寫入設定、
                也不作為任何介面的輸入或輸出參數</li>
            <li><strong>輪替</strong>：長時間運行的實例應定期重新從熵源取得新的隨機性注入內部狀態，
                避免單一狀態被長期觀察後遭到分析。這也提供了<strong>前向安全性</strong>，
                即使當前狀態意外洩漏，先前產生的序列仍無法被回推</li>
            <li><strong>銷毀</strong>：會話結束後，相關狀態應盡快從記憶體中清除，
                並且絕對不能出現在任何日誌、錯誤堆疊或除錯輸出中。
                日誌意外洩漏內部狀態，是實務上最常見也最容易被忽略的漏洞形式之一</li>
        </ul>
        <p>
            這裡有一個容易被誤解的重點：<strong>種子不可預測，不等於種子不可重複</strong>。
            高併發環境下，兩個實例即使各自的種子都來自良好的熵源，仍有極小機率碰撞。
            因此除了品質保證之外，還需要結構性的唯一性保證。這正是原子遞增計數器參與種子混合的用意：
            它不提供隨機性，但提供了確定性的不重複保證，與熵源的不可預測性形成互補。
        </p>

        <h2><i class="fa-solid fa-clipboard-list" aria-hidden="true"></i>RNG 審計追蹤（Audit Trail）</h2>
        <p>
            合規要求每一個 RNG 呼叫都必須可追蹤、可重播。在我們的系統中，
            每次 RNG 產生的隨機數都會被記錄到審計日誌中：
        </p>
        <ul>
            <li><strong>完整記錄</strong>：每局遊戲使用的所有隨機數序列都被保存</li>
            <li><strong>確定性重播</strong>：注入相同的隨機數序列，可以精確重現任何一局遊戲結果</li>
            <li><strong>獨立驗證</strong>：審計人員可以獨立驗證每局遊戲的結果是否與記錄的隨機數一致</li>
        </ul>
        <p>
            這個機制不僅滿足合規要求，也是 QA 測試的重要工具：透過注入預定義的隨機數序列，
            可以進行精確的確定性測試，覆蓋所有邊界條件。
        </p>
        <p>
            審計軌跡真正的價值在於<strong>可回溯性</strong>：當爭議發生時，能不能重建當時的完整因果鏈。
            要達成這一點，記錄的欄位必須足以在事後獨立還原結果，而不需要依賴任何當時的執行環境。
            實務上，一筆具備完整回溯能力的記錄至少需要涵蓋以下幾類資訊：
        </p>
        <ul>
            <li><strong>時序標記</strong>：單調遞增的序號與時間戳，用來確定事件的絕對順序。
                在分散式環境中，單純的牆鐘時間可能因時鐘偏移而亂序，序號才是可靠的排序依據</li>
            <li><strong>隨機數序列本身</strong>：該局消耗的每一個原始隨機值，以及它們被取用的先後順序。
                順序資訊與數值同等重要，順序錯亂就無法重現結果</li>
            <li><strong>取用上下文</strong>：每個隨機數被用來決定什麼（例如是決定符號、還是決定倍率），
                以及當時使用的取值範圍。缺少這一層，重播時就無法把數值對應回正確的決策點</li>
            <li><strong>配置版本識別</strong>：當時生效的機率表版本與數學模型版本。
                配置一旦更新，用新配置重播舊局必然得到錯誤結果，版本標記是重播正確性的前提</li>
            <li><strong>結果快照</strong>：計算出的最終結果與賠付判定，作為重播比對的基準值</li>
            <li><strong>完整性保護</strong>：對記錄內容計算雜湊並串連成鏈，使得任何事後竄改都會破壞後續所有記錄的一致性。
                審計軌跡如果可以被無痕修改，它就失去了作為證據的意義</li>
        </ul>
        <p>
            設計時的原則是<strong>只記錄可重現結果所需的資訊，不記錄內部狀態</strong>。
            審計日誌必須詳盡到足以驗證公平性，同時又不能詳盡到洩漏 RNG 的內部狀態。
            這兩個要求之間的界線，正是審計軌跡設計最需要斟酌的地方。
        </p>

        <h2><i class="fa-solid fa-shield-halved" aria-hidden="true"></i>防止客戶端操控</h2>
        <p>
            RNG 安全的另一個關鍵維度是<strong>確保客戶端無法影響隨機結果</strong>。
            這裡的設計原則非常明確：<strong>客戶端是不可信任的執行環境</strong>。
            所有在玩家裝置上執行的程式碼都可以被反編譯、被修改、被重放；
            所有從客戶端送來的資料都應該被視為攻擊者可以任意構造的輸入。
            因此正確的架構不是「驗證客戶端沒有作弊」，而是「讓客戶端在結果的計算路徑上完全沒有發言權」。
            客戶端只負責呈現伺服器已經決定好的結果，動畫與音效的播放順序不參與任何判定。
        </p>
        <p>
            基於這個前提，我們的安全審計框架涵蓋以下檢查點：
        </p>
        <ul>
            <li><strong>N1（參數隔離）</strong>：客戶端提交的任何參數（如下注金額、選擇的 Payline）
                不會影響隨機結果的產生。Spin 結果在伺服器端獨立計算</li>
            <li><strong>N2（機率表權限）</strong>：機率表的切換僅由伺服器端邏輯決定，
                客戶端無法觸發機率表變更</li>
            <li><strong>N4（跨局狀態保護）</strong>：客戶端無法寫入跨局狀態資料，
                防止透過修改遊戲狀態來操控後續結果</li>
            <li><strong>N5（種子來源驗證）</strong>：確認 RNG 種子不是由客戶端提供，
                避免玩家透過控制種子來預測結果</li>
            <li><strong>N6（併發安全）</strong>：驗證多玩家同時進行遊戲時，
                不存在共享可變狀態導致的競爭條件（Race Condition）</li>
        </ul>

        <h2><i class="fa-solid fa-certificate" aria-hidden="true"></i>GLI / BMM 認證標準</h2>
        <p>
            通過 <strong>GLI-19</strong>（互動式博弈系統技術標準）或 <strong>BMM</strong> 認證，
            RNG 需要滿足以下統計學測試：
        </p>
        <ul>
            <li><strong>卡方檢定（Chi-Square Test）</strong>：驗證輸出的均勻分佈</li>
            <li><strong>序列相關性測試（Serial Correlation）</strong>：確保連續輸出之間不存在相關性</li>
            <li><strong>Runs Test</strong>：驗證連續相同值的出現模式符合隨機預期</li>
            <li><strong>Poker Test</strong>：驗證數字組合的分佈</li>
            <li><strong>Diehard / NIST 測試套件</strong>：一系列更嚴格的統計隨機性測試</li>
        </ul>
        <p>
            理解這些檢定的<strong>角色定位</strong>同樣重要。統計檢定的本質是<strong>否證而非證明</strong>：
            它能告訴你某個序列明顯不像隨機的，卻永遠無法證明某個序列一定是隨機的。
            通過整套檢定只代表「找不到偏離隨機假設的證據」，而不代表 RNG 安全無虞。
            前面提過的那些可預測產生器，同樣能輕鬆通過絕大多數統計檢定。
        </p>
        <p>
            另外一個實務上常見的誤區，是把檢定結果當成二元的通過或失敗。
            在顯著水準 α 之下，即使 RNG 完全正常，每執行一百次檢定也預期會有約 α 比例的檢定「意外失敗」。
            因此正確的判讀方式是觀察 p 值本身的分佈：在虛無假設成立時，
            p 值應該均勻分佈於 0 到 1 之間。若某項檢定的 p 值持續集中在極端區域，
            那才是真正的警訊；反之，偶發的單次失敗屬於預期內的隨機現象，
            過度反應反而會導致對正常系統的錯誤判定。
        </p>
        <p>
            我們的 RNG 實作在內部測試中持續通過所有上述測試，並定期接受第三方認證機構的獨立審計，
            確保在整個產品生命週期中維持最高的隨機性標準。
        </p>

        <h2><i class="fa-solid fa-layer-group" aria-hidden="true"></i>分層安全架構</h2>
        <p>
            總結而言，我們的 RNG 安全架構分為三個層次：
        </p>
        <ul>
            <li><strong>底層（密碼學安全）</strong>：CSPRNG + Rejection Sampling，確保每個隨機數的品質</li>
            <li><strong>中層（系統安全）</strong>：種子管理、實例隔離、審計追蹤，防止系統層面的漏洞</li>
            <li><strong>上層（協議安全）</strong>：客戶端隔離、參數驗證、狀態保護，防止外部操控</li>
        </ul>
        <p>
            這種多層防禦的設計確保了即使某一層出現問題，其他層仍能提供保護，
            從而建立起一個穩固可靠的公平性保障體系。
        </p>
        <p>
            分層防禦之所以有效，關鍵在於各層的<strong>失效模式互相獨立</strong>。
            如果三層防護都依賴同一個假設，那麼它看似有三層，實際上仍然只有一層。
            一旦那個共同假設被打破，三層會同時失守。因此在設計時，
            我們刻意讓每一層針對不同性質的威脅：底層防的是數學上的可預測性與分佈偏差，
            中層防的是實作與併發層面的狀態污染，上層防的是來自外部的主動操控嘗試。
            三者的假設前提不重疊，才構成真正的縱深。
        </p>
        <p>
            最後值得強調的是，隨機性的品質是<strong>不可觀測的</strong>。
            一個有缺陷的 RNG 在單局結果上看不出任何異樣，只有在大量樣本的統計分佈中才會顯露。
            這意味著我們無法依賴事後的人工檢視來發現問題，只能依賴設計階段的正確性、
            自動化的持續統計監控，以及完整的審計軌跡三者結合。
            公平性不是一個上線前檢查一次就能永久成立的性質，而是需要在整個產品生命週期中持續驗證的承諾。
        </p>
