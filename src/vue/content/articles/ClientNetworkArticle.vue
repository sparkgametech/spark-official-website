<template>
    <div class="blog-article">
        <h2><i class="fa-solid fa-network-wired" aria-hidden="true"></i>通訊協議與斷線重連</h2>
        <p>
            一款遊戲是否經得起真實環境的考驗，取決於三個玩家幾乎不會注意到的系統：
            <strong>通訊層、資源層、介面層級管理</strong>。它們做得好時完全沒有存在感，做不好時每個缺陷都會被放大。
        </p>
        <p>
            其中通訊是整個遊戲體驗的關鍵基礎設施。不同於一般 Web 應用的請求—回應模式，
            老虎機遊戲需要<strong>持久連線</strong>來保證即時性與狀態一致性。
        </p>
        <h3>長連線與心跳機制</h3>
        <p>
            客端與伺服器之間通過 WebSocket 建立長連線，並定期交換<strong>心跳封包</strong>以偵測連線是否健康；
            若在超時時間內未收到回應，則判定連線已斷開並啟動重連流程。
            間隔的選擇是個取捨：太長會延遲數秒才察覺斷線，太短則在行動網路下產生不必要的耗電。
            我們讓心跳與實際流量互斥。間隔內若已有正常封包往返，這次心跳就跳過。
        </p>
        <h3>一局 Spin 的通訊流程</h3>
        <MermaidDiagram id="comm-flow" :chart="commFlowChart"/>
        <p>
            這個流程看似簡單，但細節中隱藏著多種邊界情境：
        </p>
        <ul>
            <li><strong>請求超時</strong>：伺服器在設定時間內未回應時，客端需決定重送或提示錯誤。重送必須攜帶原始請求的識別碼，讓伺服器能辨認這是重試而非新的一局</li>
            <li><strong>重複回應</strong>：網路抖動可能導致同一請求收到多次回應，客端必須透過局號進行去重</li>
            <li><strong>亂序到達</strong>：在極端情況下，後發的封包可能先到達，需要序號機制保證處理順序</li>
        </ul>
        <p>
            這三種情境有一個共通的設計原則：<strong>讓所有關鍵操作具備冪等性</strong>。
            同一請求無論送出幾次、回應無論收到幾次，最終呈現給玩家的結果都必須一致。
            把冪等性設計在協議層，遠比在每一處呼叫點各自防禦來得可靠。
        </p>
        <h3>斷線重連策略</h3>
        <p>
            斷線在行動網路環境中極為常見：切換基地台、進入電梯、網路瞬斷。
            良好的重連策略必須能<strong>無感恢復</strong>遊戲狀態。核心機制如下：
        </p>
        <ul>
            <li><strong>局號比對</strong>：客端記錄最後完成的局號，重連時發送給伺服器。伺服器比對後回傳差異資料。若有已結算但客端未收到的結果，一併推送</li>
            <li><strong>狀態快照恢復</strong>：伺服器回傳當前遊戲的完整狀態快照（包含未結算的免費遊戲剩餘局數、累積獎池進度等），客端據此恢復到斷線前的場景</li>
            <li><strong>指數退避重連</strong>：重連嘗試採用指數退避策略（1 秒、2 秒、4 秒、8 秒⋯⋯），避免大量客端同時重連造成伺服器負載尖峰</li>
        </ul>
        <p>
            恢復的難點其實不在資料而在<strong>演出</strong>：直接把最終畫面貼上去很突兀，
            整段重播又會讓已知道結果的玩家覺得冗長。我們依斷線發生的階段決定策略：
            展示階段之前斷線就完整重播，之後斷線則快進到終態。
        </p>
        <h3>數值精度</h3>
        <p>
            客端所有數值均採用<strong>整數運算</strong>，以最小單位為基本刻度避免浮點數的累積誤差，
            只有顯示時才轉換為帶小數點的格式。這個原則必須貫徹到每個中間環節，包括數字滾動動畫的插值。
        </p>

        <h2><i class="fa-solid fa-language" aria-hidden="true"></i>資源管理與多語系</h2>
        <p>
            一款老虎機遊戲的資源量可能相當龐大：數百張圖片精靈（包含不同解析度的版本）、
            骨骼動畫資料、音效檔案、字型檔案等，如何高效管理直接影響載入速度與記憶體佔用。
            資源載入採用<strong>分階段漸進式</strong>策略：
        </p>
        <ul>
            <li><strong>載入畫面階段</strong>：僅載入進度條介面、品牌標誌等最小集合，讓畫面盡快呈現</li>
            <li><strong>主遊戲階段</strong>：載入主場景的必要資源，包含滾輪符號、背景圖、基礎音效、介面元素。此階段完成後玩家即可開始遊戲</li>
            <li><strong>延遲載入階段</strong>：在背景靜默載入特殊功能的資源，包含大獎動畫、免費遊戲場景、特殊音效等，在首次觸發前完成即可</li>
        </ul>
        <p>
            延遲載入需要一道保險：若特殊功能被觸發時資源尚未就緒，流程不能中斷，
            而是插入一段可延長的過場演出來爭取時間。這也是為什麼場景轉換動畫通常設計成可無縫循環。
        </p>
        <h3>流程切換與資源切換</h3>
        <p>
            老虎機的資源需求並非單一集合，而是隨著遊戲流程切換而變動：
        </p>
        <MermaidDiagram id="multi-flow" :chart="multiFlowChart"/>
        <p>
            每一次流程切換同時也是一次資源切換：進入免費遊戲要載入專屬背景與符號變體，
            退出時則要決定哪些釋放、哪些保留在快取中。判準是觸發頻率：
            高頻流程的資源留在記憶體，低頻的特殊玩法資源在退出時釋放。
        </p>
        <h3>三層資源覆蓋機制</h3>
        <p>
            配合三層式架構，資源系統也支援<strong>三層覆蓋</strong>：
        </p>
        <ul>
            <li><strong>引擎層</strong>：提供通用預設素材</li>
            <li><strong>框架層</strong>：覆蓋為適合老虎機品類的標準素材</li>
            <li><strong>遊戲層</strong>：個別遊戲再覆蓋成自訂版本</li>
        </ul>
        <p>
            載入器查找時從遊戲層開始逐層向下回退，讓開發者只需替換需要自訂的部分，其餘自動繼承上層預設值。
        </p>
        <h3>多語系支援</h3>
        <p>
            多語系支援遠不止「替換文字」這麼簡單，它涉及以下多個維度：
        </p>
        <ul>
            <li><strong>翻譯對照表</strong>：所有顯示文字透過鍵值對照表管理並支援參數插值，初始化時依語系載入對應翻譯檔</li>
            <li><strong>語系專屬素材</strong>：某些視覺元素無法單純靠文字替換（如包含文字的圖片、特定文化風格的裝飾），需要為特定語系準備獨立版本</li>
            <li><strong>右至左排版（RTL）</strong>：阿拉伯語、希伯來語等語系需要鏡像翻轉整個介面佈局，不只是文字方向，按鈕位置、進度條方向也可能需要調整</li>
            <li><strong>回退機制</strong>：翻譯鍵在目標語系不存在時，依序回退到區域預設語言、英語，確保永遠不會顯示原始鍵值</li>
            <li><strong>版面彈性</strong>：同一句話在不同語言的長度差異可能達兩倍以上，按鈕與標籤必須能自動縮放字級或換行</li>
        </ul>

        <h2><i class="fa-solid fa-volume-high" aria-hidden="true"></i>音效系統設計</h2>
        <p>
            音效對老虎機遊戲體驗的影響經常被低估，精心設計的音效系統能大幅提升沉浸感與回饋感。
            我們的音效架構將所有聲音分為<strong>三個獨立的聲道</strong>管理：
        </p>
        <ul>
            <li><strong>背景音樂</strong>：持續循環，同一時間只有一首在播</li>
            <li><strong>短音效</strong>：由事件觸發，可同時播放多個</li>
            <li><strong>語音</strong>：需要隨語系切換素材</li>
        </ul>
        <p>
            三個聲道擁有獨立的音量控制，玩家可以分別調整。
        </p>
        <h3>音效與遊戲狀態的同步</h3>
        <p>
            音效系統與遊戲狀態機深度整合，確保聲音與畫面的精準同步：
        </p>
        <ul>
            <li><strong>滾輪聲效</strong>：旋轉中的持續低頻聲、每欄停止時的敲擊聲、聽牌時的懸念音效，都由狀態機的階段切換事件觸發</li>
            <li><strong>中獎回饋</strong>：小獎播放簡短的硬幣聲，數值越大音效越隆重，從歡快的鈴聲升級到完整的慶祝樂曲</li>
            <li><strong>場景切換配樂</strong>：從主遊戲進入免費遊戲時，背景音樂需要自然過渡而非突兀切換</li>
        </ul>
        <p>
            停輪聲效的對齊有個實務細節：聲音應該對齊<strong>滾輪接觸目標位置的瞬間</strong>，
            而不是整段動畫的結束時刻。過衝與回彈發生在接觸之後，晚放就會慢半拍。
        </p>
        <h3>交叉淡入淡出與防疊加</h3>
        <p>
            場景切換時，音效系統會執行<strong>交叉淡入淡出</strong>：當前場景的背景音樂在設定時間內漸弱，
            同時新場景的音樂漸強，交叉曲線可獨立設定以確保過渡自然。
        </p>
        <p>
            另一個常見問題是疊加：快速節奏中同一音效可能極短時間內被觸發多次（例如連續的中獎線展示），
            多個實例疊加會產生刺耳的音量暴增。音效系統以三種機制防止：
        </p>
        <ul>
            <li><strong>最小間隔限制</strong>：同一音效在設定的時間間隔內不會重複觸發</li>
            <li><strong>實例數量上限</strong>：限制同一音效同時播放的最大實例數，超出時替換最早的實例</li>
            <li><strong>優先權機制</strong>：高優先權的音效可以中斷低優先權的音效，確保重要回饋不被淹沒</li>
        </ul>

        <h2><i class="fa-solid fa-layer-group" aria-hidden="true"></i>介面層級設計</h2>
        <p>
            老虎機遊戲的介面層級管理比一般應用程式更複雜：各種元素會在不同時機出現和消失，
            它們之間存在嚴格的<strong>層級關係與互斥規則</strong>。我們採用四層架構：
        </p>
        <ul>
            <li><strong>遊戲介面層</strong>：最底層的常駐介面，包含滾輪區域、下注面板、數值顯示、功能按鈕等，執行期間始終可見</li>
            <li><strong>功能面板層</strong>：覆蓋其上的賠付表、規則說明、歷史紀錄、設定面板等。開啟時遮蓋畫面但不中斷遊戲邏輯</li>
            <li><strong>慶祝特效層</strong>：大獎慶祝動畫、特殊功能觸發的全屏特效等，佔據整個畫面並遮蓋所有下方元素</li>
            <li><strong>系統訊息層</strong>：最上層，顯示網路錯誤等系統級通知。這些訊息必須始終可見，不被任何遊戲內容遮蓋</li>
        </ul>
        <h3>互斥鎖機制</h3>
        <p>
            層級之間存在嚴格的<strong>互斥鎖定規則</strong>，防止多個浮層同時出現造成混亂：
        </p>
        <ul>
            <li><strong>同層互斥</strong>：同一層級內一次只能顯示一個面板。開啟賠付表時若玩家點擊設定，賠付表必須先關閉</li>
            <li><strong>跨層阻斷</strong>：高優先層級活躍時，低優先層級的互動被暫時禁用。慶祝動畫播放時無法開啟功能面板</li>
            <li><strong>佇列機制</strong>：系統訊息出現在最上層時，其他層級的開啟請求會被暫存到佇列，待訊息關閉後依序處理</li>
            <li><strong>強制穿透</strong>：特定的系統級訊息（如嚴重錯誤）可以穿透任何互斥鎖，立即顯示並凍結所有下層操作</li>
        </ul>
        <p>
            這套機制確保介面在任何情境下都保持有序、可預測。
            即使在極端情況下，例如大獎慶祝動畫播放期間斷線，通訊層的錯誤訊息會穿透到最上層，
            慶祝動畫則被凍結而非中止，待玩家確認後從凍結處續播。三個支撐系統在這一刻的協作，
            正是整套架構真正被驗證的地方。
        </p>

        <p>
            這些支撐系統之所以能彼此協作而不糾纏，前提是有一套清楚的分層架構與狀態機定義；
            而它們所服務的視覺主體，也就是滾輪的動畫曲線與停輪節奏，則有自己獨立的設計方法。
            這兩個主題我們在同系列的另外兩篇文章中分別展開。
        </p>

